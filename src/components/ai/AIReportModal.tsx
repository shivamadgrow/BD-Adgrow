import React, { useState } from 'react';
import { Business, AIResearchReport } from '@/types';
import { Modal } from '../ui/Modal';
import { Badge } from '../ui/Badge';
import { Button } from '../ui/Button';
import { generateAIResearchReport } from '@/lib/services/ai-agent-service';
import {
  Sparkles,
  CheckCircle2,
  Copy,
  Check,
  Mail,
  Phone,
  Linkedin,
  MessageSquare,
  HelpCircle,
  TrendingUp,
  Target,
  FileText,
  Plus,
} from 'lucide-react';

interface AIReportModalProps {
  business: Business | null;
  isOpen: boolean;
  onClose: () => void;
  onAddToCRM: (b: Business) => void;
  inCrm: boolean;
}

export const AIReportModal: React.FC<AIReportModalProps> = ({
  business,
  isOpen,
  onClose,
  onAddToCRM,
  inCrm,
}) => {
  const [activeOutreachTab, setActiveOutreachTab] = useState<'email' | 'phone' | 'linkedin' | 'whatsapp'>('email');
  const [copiedKey, setCopiedKey] = useState<string | null>(null);

  if (!business) return null;

  const report: AIResearchReport = generateAIResearchReport(business);

  const handleCopy = (text: string, key: string) => {
    navigator.clipboard.writeText(text);
    setCopiedKey(key);
    setTimeout(() => setCopiedKey(null), 2000);
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title="AI Business Intelligence Dossier & Sales Playbook"
      subtitle={`Generated by Ad Grow BD Agent • ${business.name}`}
      maxWidth="4xl"
      footer={
        <div className="flex items-center justify-between w-full">
          <div className="flex items-center gap-2 text-xs text-slate-500">
            <span className="w-2 h-2 rounded-full bg-emerald-500" />
            <span>Facts strictly verified against public listings. Zero hallucinated data.</span>
          </div>
          <div className="flex items-center gap-2">
            <Button variant="outline" size="sm" onClick={onClose}>
              Close
            </Button>
            {!inCrm && (
              <Button
                variant="primary"
                size="sm"
                leftIcon={<Plus className="w-3.5 h-3.5" />}
                onClick={() => {
                  onAddToCRM(business);
                  onClose();
                }}
              >
                Add to CRM Pipeline
              </Button>
            )}
          </div>
        </div>
      }
    >
      <div className="space-y-6">
        {/* Top Summary Banner */}
        <div className="p-4 rounded-xl bg-gradient-to-r from-blue-900 via-indigo-900 to-slate-900 text-white flex items-center justify-between flex-wrap gap-4">
          <div>
            <div className="flex items-center gap-2">
              <Sparkles className="w-4 h-4 text-amber-400" />
              <span className="text-xs font-semibold uppercase tracking-wider text-blue-200">
                Strategic Intelligence Dossier
              </span>
            </div>
            <h3 className="text-lg font-bold mt-1 text-white">{business.name}</h3>
            <p className="text-xs text-slate-300">
              {business.category} • {business.location.city}, {business.location.countryName}
            </p>
          </div>
          <div className="text-right">
            <div className="text-xs text-blue-200">Opportunity Score</div>
            <div className="text-2xl font-black text-amber-400">{business.score.totalScore}/100</div>
          </div>
        </div>

        {/* Section 1: Verified Observations vs Inferences */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {/* Verified Facts */}
          <div className="p-4 rounded-xl border border-slate-200 bg-white shadow-xs">
            <h4 className="text-xs font-bold uppercase tracking-wider text-slate-700 flex items-center gap-2 mb-3">
              <CheckCircle2 className="w-4 h-4 text-emerald-600" />
              1. Verified Observations (Direct Evidence)
            </h4>
            <ul className="space-y-2 text-xs text-slate-700">
              {report.verifiedFacts.map((fact, idx) => (
                <li key={idx} className="flex items-start gap-2">
                  <span className="text-emerald-500 font-bold shrink-0">✓</span>
                  <span>{fact}</span>
                </li>
              ))}
            </ul>
          </div>

          {/* Observable Gaps */}
          <div className="p-4 rounded-xl border border-amber-200 bg-amber-50/40 shadow-xs">
            <h4 className="text-xs font-bold uppercase tracking-wider text-amber-900 flex items-center gap-2 mb-3">
              <Target className="w-4 h-4 text-amber-600" />
              2. Identified Opportunity Gaps
            </h4>
            <div className="space-y-2.5">
              {report.digitalPresenceGaps.map((g, idx) => (
                <div key={idx} className="text-xs">
                  <div className="font-semibold text-amber-950 flex items-center justify-between">
                    <span>{g.gap}</span>
                    <span className="text-[10px] uppercase font-bold text-emerald-700 bg-emerald-100/80 px-1.5 py-0.2 rounded">
                      {g.confidence} confidence
                    </span>
                  </div>
                  <p className="text-slate-600 text-[11px] mt-0.5">{g.evidence}</p>
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Section 2: Recommended Sales Strategy */}
        <div className="p-4 rounded-xl border border-slate-200 bg-slate-50">
          <h4 className="text-xs font-bold uppercase tracking-wider text-slate-800 flex items-center gap-2 mb-2">
            <TrendingUp className="w-4 h-4 text-blue-600" />
            3. Recommended Agency Pitch Angle
          </h4>
          <div className="text-xs text-slate-700 space-y-1.5">
            <div>
              <span className="font-semibold text-slate-900">Primary Service: </span>
              <span className="text-blue-700 font-bold">{report.salesStrategy.primaryServiceToPitch}</span>
            </div>
            <div>
              <span className="font-semibold text-slate-900">Value Proposition: </span>
              <span>{report.salesStrategy.valueProposition}</span>
            </div>
            <div>
              <span className="font-semibold text-slate-900">Reasoning: </span>
              <span className="text-slate-600">{report.salesStrategy.pitchReasoning}</span>
            </div>
          </div>

          {/* Suggested Discovery Questions */}
          <div className="mt-4 pt-3 border-t border-slate-200">
            <h5 className="text-[11px] font-bold uppercase tracking-wider text-slate-500 mb-2 flex items-center gap-1.5">
              <HelpCircle className="w-3.5 h-3.5 text-slate-400" />
              Suggested Discovery Call Questions
            </h5>
            <div className="grid grid-cols-1 md:grid-cols-2 gap-2 text-xs">
              {report.salesStrategy.suggestedDiscoveryQuestions.map((q, idx) => (
                <div key={idx} className="p-2.5 rounded-lg bg-white border border-slate-200 text-slate-700">
                  {q}
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Section 3: Personalized Outreach Drafts */}
        <div className="rounded-xl border border-slate-200 overflow-hidden bg-white">
          <div className="flex items-center justify-between px-4 py-2.5 bg-slate-100 border-b border-slate-200">
            <div className="flex items-center gap-1 text-xs">
              <button
                onClick={() => setActiveOutreachTab('email')}
                className={`inline-flex items-center gap-1.5 px-3 py-1.5 rounded-md font-medium transition-colors ${
                  activeOutreachTab === 'email' ? 'bg-white shadow-xs text-slate-900 font-bold' : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                <Mail className="w-3.5 h-3.5 text-blue-600" />
                Cold Email
              </button>
              <button
                onClick={() => setActiveOutreachTab('phone')}
                className={`inline-flex items-center gap-1.5 px-3 py-1.5 rounded-md font-medium transition-colors ${
                  activeOutreachTab === 'phone' ? 'bg-white shadow-xs text-slate-900 font-bold' : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                <Phone className="w-3.5 h-3.5 text-emerald-600" />
                Cold Call Script
              </button>
              <button
                onClick={() => setActiveOutreachTab('linkedin')}
                className={`inline-flex items-center gap-1.5 px-3 py-1.5 rounded-md font-medium transition-colors ${
                  activeOutreachTab === 'linkedin' ? 'bg-white shadow-xs text-slate-900 font-bold' : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                <Linkedin className="w-3.5 h-3.5 text-sky-600" />
                LinkedIn InMail
              </button>
              <button
                onClick={() => setActiveOutreachTab('whatsapp')}
                className={`inline-flex items-center gap-1.5 px-3 py-1.5 rounded-md font-medium transition-colors ${
                  activeOutreachTab === 'whatsapp' ? 'bg-white shadow-xs text-slate-900 font-bold' : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                <MessageSquare className="w-3.5 h-3.5 text-teal-600" />
                WhatsApp Message
              </button>
            </div>

            <Button
              variant="outline"
              size="sm"
              leftIcon={copiedKey === activeOutreachTab ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
              onClick={() => {
                let textToCopy = '';
                if (activeOutreachTab === 'email') {
                  textToCopy = `Subject: ${report.outreachDrafts.emailSubject}\n\n${report.outreachDrafts.emailBody}`;
                } else if (activeOutreachTab === 'phone') {
                  textToCopy = report.outreachDrafts.phoneColdScript;
                } else if (activeOutreachTab === 'linkedin') {
                  textToCopy = report.outreachDrafts.linkedinInMail;
                } else if (activeOutreachTab === 'whatsapp') {
                  textToCopy = report.outreachDrafts.whatsappMessage;
                }
                handleCopy(textToCopy, activeOutreachTab);
              }}
            >
              {copiedKey === activeOutreachTab ? 'Copied!' : 'Copy Draft'}
            </Button>
          </div>

          <div className="p-4 text-xs font-mono bg-slate-50/50 whitespace-pre-wrap leading-relaxed text-slate-800">
            {activeOutreachTab === 'email' && (
              <div>
                <div className="pb-2 mb-2 border-b border-slate-200 font-sans font-semibold text-slate-900">
                  Subject: {report.outreachDrafts.emailSubject}
                </div>
                {report.outreachDrafts.emailBody}
              </div>
            )}
            {activeOutreachTab === 'phone' && report.outreachDrafts.phoneColdScript}
            {activeOutreachTab === 'linkedin' && report.outreachDrafts.linkedinInMail}
            {activeOutreachTab === 'whatsapp' && report.outreachDrafts.whatsappMessage}
          </div>
        </div>
      </div>
    </Modal>
  );
};
